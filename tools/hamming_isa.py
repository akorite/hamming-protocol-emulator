def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--emit", action="store_true",
                    help="write src/hamming_defs.vh and docs/ISA.md")
    ap.add_argument("--check", action="store_true",
                    help="fail if generated files are not up to date")
    args = ap.parse_args(argv)
    if not (args.emit or args.check):
        ap.print_help()
        return 0

    targets = [
        (ROOT / "src" / "hamming_defs.vh", emit_verilog()),
        (ROOT / "docs" / "ISA.md", emit_docs()),
    ]
    stale = []
    for path, text in targets:
        old = path.read_text() if path.exists() else None
        if old != text:
            stale.append(path)
            if args.emit:
                path.write_text(text)
                print(f"{path}: written")
    if args.check and stale:
        for p in stale:
            print(f"{p}: STALE - run `python -m tools.hamming_isa --emit`",
                  file=sys.stderr)
        return 1
    if args.emit and not stale:
        print("generated files already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
