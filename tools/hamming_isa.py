"""Hamming protocol-core ISA: single canonical encoding/CSR specification.

This module is the single source of truth for the 16-bit Hamming core ISA.
`tools/hamming_asm.py` (assembler/disassembler), `tools/hamming_iss.py`
(Golden ISS), `src/hamming_defs.vh` (RTL constants) and `docs/ISA.md` are all
derived from the tables below so they can never drift.

Instruction formats (16 bits, [15:12] = major opcode):

  0x0 ALU     [11:8]=alu_op  [7:6]=rd  [5:4]=rs  [3:0]=0
  0x1 LDI8    [11:10]=rd     [9:8]=half(0=lo,1=hi)  [7:0]=imm8
  0x2 PIN     [11:8]=sub     sub 0 PIN_OUT / 1 PIN_OE: [7:4]=mask4 [3:0]=val4
                             sub 2 PIN_IN  / 3 LUT_READ: [7:4]=src  [3:2]=rd [1:0]=0
  0x3 TIMING  [11:8]=sub     0 WAIT_PHASE rs:  [3:2]=rs  [7:4]=0 [1:0]=0
                             1 WAIT_PHASE imm: [7:0]=imm8
                             2 SYNC_EVENT:     [7:4]=ev_mask4 [3:2]=timeout reg [1:0]=0
                             3 SET_ANCHOR:     [7:0]=imm8 (anchor <= timer+imm8)
                             4 READ_TIMER:     [7:4]=sel [3:2]=rd [1:0]=0
  0x4 BCU     [11:8]=sub     0 BCU_TX [3:2]=rs   1 BCU_RX [3:2]=rd
                             2 BCU_CTRL [7:0]=imm8   3 BCU_STAT [3:2]=rd
                             4 BCU_CRC_RD [7:6]=sel(0=lo,1=hi) [5:4]=0 [3:2]=rd
  0x5 MEM     [11:8]=sub     0..4 = LD_DMEM_W/ST_DMEM_W/LD_DMEM_B/ST_DMEM_B/LD_IMEM
                             [7:6]=ra(base) [5:4]=imm2 [3:2]=rt [1:0]=0
  0x6 CSR_RD  [11:10]=rd     [9:8]=0  [7:0]=csr_addr
  0x7 CSR_WR  [11:10]=rs     [9:8]=0  [7:0]=csr_addr
  0x8 JMP     [11:10]=0      [9:0]=pc10
  0x9 BR      [11:10]=kind   0 JZ / 1 JNZ / 3 CALL: [9:0]=pc10
                             2 JEV: [9:6]=ev_mask4 [5:4]=0 [3:2]=rs (jump to reg)
  0xA MISC    [11:8]=sub     0 RET / 1 HALT / 2 NOP   [7:0]=0
  0xB..0xF    reserved       (assembler rejects; decoder returns None)

`python -m tools.hamming_isa --emit` regenerates `src/hamming_defs.vh` and
`docs/ISA.md`; `--check` verifies the checked-in copies are up to date.
"""

