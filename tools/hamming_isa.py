def signed20(value):
    """Interpret the low 20 bits of `value` as a signed 20-bit integer."""
    value &= TIMER_MASK
    return value - (1 << TIMER_W) if value & (1 << (TIMER_W - 1)) else value


# ---------------------------------------------------------------------------
# Encoders (all take Python ints; unused field positions are always emitted 0)
# ---------------------------------------------------------------------------

def _chk(name, value, bits):
    if not 0 <= value < (1 << bits):
        raise ValueError(f"{name}={value} does not fit in {bits} bits")
    return value


def enc_alu(alu_op, rd, rs):
    return (MAJOR_ALU << 12 | _chk("alu_op", alu_op, 4) << 8 |
            _chk("rd", rd, 2) << 6 | _chk("rs", rs, 2) << 4)


def enc_ldi8(rd, half, imm8):
    return (MAJOR_LDI8 << 12 | _chk("rd", rd, 2) << 10 |
            _chk("half", half, 2) << 8 | _chk("imm8", imm8, 8))


def enc_pin_out(mask4, val4):
    return (MAJOR_PIN << 12 | PIN_OPS["pin_out"] << 8 |
            _chk("mask4", mask4, 4) << 4 | _chk("val4", val4, 4))


def enc_pin_oe(mask4, val4):
    return (MAJOR_PIN << 12 | PIN_OPS["pin_oe"] << 8 |
            _chk("mask4", mask4, 4) << 4 | _chk("val4", val4, 4))


def enc_pin_in(rd, pin):
    return (MAJOR_PIN << 12 | PIN_OPS["pin_in"] << 8 |
            _chk("pin", pin, 4) << 4 | _chk("rd", rd, 2) << 2)


def enc_lut_read(rd, lut):
    return (MAJOR_PIN << 12 | PIN_OPS["lut_read"] << 8 |
            _chk("lut", lut, 4) << 4 | _chk("rd", rd, 2) << 2)


def enc_wait_rs(rs):
    return MAJOR_TIMING << 12 | TIM_OPS["wait_phase_r"] << 8 | _chk("rs", rs, 2) << 2


def enc_wait_imm(imm8):
    return MAJOR_TIMING << 12 | TIM_OPS["wait_phase_i"] << 8 | _chk("imm8", imm8, 8)


def enc_sync_event(mask4, rt):
    return (MAJOR_TIMING << 12 | TIM_OPS["sync_event"] << 8 |
            _chk("mask4", mask4, 4) << 4 | _chk("rt", rt, 2) << 2)


def enc_set_anchor(imm8):
    return MAJOR_TIMING << 12 | TIM_OPS["set_anchor"] << 8 | _chk("imm8", imm8, 8)


def enc_read_timer(rd, sel):
    return (MAJOR_TIMING << 12 | TIM_OPS["read_timer"] << 8 |
            _chk("sel", sel, 4) << 4 | _chk("rd", rd, 2) << 2)


def enc_bcu_tx(rs):
    return MAJOR_BCU << 12 | BCU_OPS["bcu_tx"] << 8 | _chk("rs", rs, 2) << 2


def enc_bcu_rx(rd):
    return MAJOR_BCU << 12 | BCU_OPS["bcu_rx"] << 8 | _chk("rd", rd, 2) << 2


def enc_bcu_ctrl(imm8):
    return MAJOR_BCU << 12 | BCU_OPS["bcu_ctrl"] << 8 | _chk("imm8", imm8, 8)


def enc_bcu_stat(rd):
    return MAJOR_BCU << 12 | BCU_OPS["bcu_stat"] << 8 | _chk("rd", rd, 2) << 2


def enc_bcu_crc_rd(rd, sel):
    return (MAJOR_BCU << 12 | BCU_OPS["bcu_crc_rd"] << 8 |
            _chk("sel", sel, 2) << 6 | _chk("rd", rd, 2) << 2)


def enc_mem(sub, ra, imm2, rt):
    return (MAJOR_MEM << 12 | _chk("sub", sub, 4) << 8 |
            _chk("ra", ra, 2) << 6 | _chk("imm2", imm2, 2) << 4 |
            _chk("rt", rt, 2) << 2)


def enc_csr_rd(rd, addr):
    return MAJOR_CSR_RD << 12 | _chk("rd", rd, 2) << 10 | _chk("addr", addr, 8)


def enc_csr_wr(rs, addr):
    return MAJOR_CSR_WR << 12 | _chk("rs", rs, 2) << 10 | _chk("addr", addr, 8)


def enc_jmp(pc10):
    return MAJOR_JMP << 12 | _chk("pc10", pc10, 10)


def enc_br(kind, pc10):
    return MAJOR_BR << 12 | _chk("kind", kind, 2) << 10 | _chk("pc10", pc10, 10)


def enc_jev(mask4, rs):
    return (MAJOR_BR << 12 | BR_OPS["jev"] << 10 |
            _chk("mask4", mask4, 4) << 6 | _chk("rs", rs, 2) << 2)


def enc_misc(sub):
    return MAJOR_MISC << 12 | _chk("sub", sub, 4) << 8


# ---------------------------------------------------------------------------
# Decoder: decode(word) -> (mnemonic, operand-dict) or None for
# reserved-major / non-zero-must-be-zero-field words.
# ---------------------------------------------------------------------------

def decode(word):
    """Decode one 16-bit instruction word.

    Returns (mnemonic, operands) where operands is a dict of field names, or
    None when the word is not a legal instruction (reserved major, reserved
    sub-op, or a must-be-zero field is set).  Legal words re-encode
    bit-identically via `encode(mnemonic, **operands)`-equivalent calls.
    """
    word &= 0xFFFF
    major = word >> 12
    sub = (word >> 8) & 0xF

    if major == MAJOR_ALU:
        if sub > 0xB or word & 0xF:
            return None
        rs = (word >> 4) & 3
        # Unary ops ignore rs; the field is must-be-zero so encodings stay
        # unique (non-zero rs words are illegal, decoded as .word).
        if ALU_NAMES[sub] in ALU_UNARY and rs:
            return None
        return (ALU_NAMES[sub], {"rd": (word >> 6) & 3, "rs": rs})
    if major == MAJOR_LDI8:
        half = (word >> 8) & 3
        if half > 1:
            return None
        return ("ldi8", {"rd": (word >> 10) & 3, "half": half,
                         "imm8": word & 0xFF})
    if major == MAJOR_PIN:
        if sub == PIN_OPS["pin_out"] or sub == PIN_OPS["pin_oe"]:
            return (PIN_NAMES[sub], {"mask4": (word >> 4) & 0xF, "val4": word & 0xF})
        if sub in (PIN_OPS["pin_in"], PIN_OPS["lut_read"]):
            if word & 0x3:
                return None
            field = "pin" if sub == PIN_OPS["pin_in"] else "lut"
            return (PIN_NAMES[sub], {field: (word >> 4) & 0xF, "rd": (word >> 2) & 3})
        return None
    if major == MAJOR_TIMING:
        if sub == TIM_OPS["wait_phase_r"]:
            if word & 0xF3:
                return None
            return ("wait_phase", {"rs": (word >> 2) & 3})
        if sub == TIM_OPS["wait_phase_i"]:
            return ("wait_phase", {"imm8": word & 0xFF})
        if sub == TIM_OPS["sync_event"]:
            if word & 0x3:
                return None
            return ("sync_event", {"mask4": (word >> 4) & 0xF, "rt": (word >> 2) & 3})
        if sub == TIM_OPS["set_anchor"]:
            return ("set_anchor", {"imm8": word & 0xFF})
        if sub == TIM_OPS["read_timer"]:
            if word & 0x3 or ((word >> 4) & 0xF) > 1:
                return None
            return ("read_timer", {"rd": (word >> 2) & 3, "sel": (word >> 4) & 0xF})
        return None
    if major == MAJOR_BCU:
        if sub in (BCU_OPS["bcu_tx"], BCU_OPS["bcu_rx"], BCU_OPS["bcu_stat"]):
            if word & 0xF3:
                return None
            name = BCU_NAMES[sub]
            key = "rs" if sub == BCU_OPS["bcu_tx"] else "rd"
            return (name, {key: (word >> 2) & 3})
        if sub == BCU_OPS["bcu_ctrl"]:
            return ("bcu_ctrl", {"imm8": word & 0xFF})
        if sub == BCU_OPS["bcu_crc_rd"]:
            if word & 0x33 or (word >> 6) & 3 > 1:
                return None
            return ("bcu_crc_rd", {"rd": (word >> 2) & 3, "sel": (word >> 6) & 3})
        return None
    if major == MAJOR_MEM:
        if sub > MEM_OPS["ld_imem"] or word & 0x3:
            return None
        return (MEM_NAMES[sub], {"ra": (word >> 6) & 3, "imm2": (word >> 4) & 3,
                                 "rt": (word >> 2) & 3})
    if major == MAJOR_CSR_RD:
        if word & 0x300:
            return None
        return ("csr_rd", {"rd": (word >> 10) & 3, "addr": word & 0xFF})
    if major == MAJOR_CSR_WR:
        if word & 0x300:
            return None
        return ("csr_wr", {"rs": (word >> 10) & 3, "addr": word & 0xFF})
    if major == MAJOR_JMP:
        if word & 0xC00:
            return None
        return ("jmp", {"pc10": word & PC_MASK})
    if major == MAJOR_BR:
        kind = (word >> 10) & 3
        if kind == BR_OPS["jev"]:
            if word & 0x30:
                return None
            return ("jev", {"mask4": (word >> 6) & 0xF, "rs": (word >> 2) & 3})
        return (BR_NAMES[kind], {"pc10": word & PC_MASK})
    if major == MAJOR_MISC:
        if sub > MISC_OPS["nop"] or word & 0xFF:
            return None
        return (MISC_NAMES[sub], {})
    return None  # 0xB..0xF reserved


def encode(mnemonic, **ops):
    """Re-encode a decoded (mnemonic, operands) pair bit-identically."""
    if mnemonic in ALU_OPS:
        return enc_alu(ALU_OPS[mnemonic], ops["rd"], ops["rs"])
    if mnemonic == "ldi8":
        return enc_ldi8(ops["rd"], ops["half"], ops["imm8"])
    if mnemonic == "pin_out":
        return enc_pin_out(ops["mask4"], ops["val4"])
    if mnemonic == "pin_oe":
        return enc_pin_oe(ops["mask4"], ops["val4"])
    if mnemonic == "pin_in":
        return enc_pin_in(ops["rd"], ops["pin"])
    if mnemonic == "lut_read":
        return enc_lut_read(ops["rd"], ops["lut"])
    if mnemonic == "wait_phase":
        if "rs" in ops:
            return enc_wait_rs(ops["rs"])
        return enc_wait_imm(ops["imm8"])
    if mnemonic == "sync_event":
        return enc_sync_event(ops["mask4"], ops["rt"])
    if mnemonic == "set_anchor":
        return enc_set_anchor(ops["imm8"])
    if mnemonic == "read_timer":
        return enc_read_timer(ops["rd"], ops["sel"])
    if mnemonic in BCU_OPS:
        if mnemonic == "bcu_tx":
            return enc_bcu_tx(ops["rs"])
        if mnemonic == "bcu_rx":
            return enc_bcu_rx(ops["rd"])
        if mnemonic == "bcu_ctrl":
            return enc_bcu_ctrl(ops["imm8"])
        if mnemonic == "bcu_stat":
            return enc_bcu_stat(ops["rd"])
        return enc_bcu_crc_rd(ops["rd"], ops["sel"])
    if mnemonic in MEM_OPS:
        return enc_mem(MEM_OPS[mnemonic], ops["ra"], ops["imm2"], ops["rt"])
    if mnemonic == "csr_rd":
        return enc_csr_rd(ops["rd"], ops["addr"])
    if mnemonic == "csr_wr":
        return enc_csr_wr(ops["rs"], ops["addr"])
    if mnemonic == "jmp":
        return enc_jmp(ops["pc10"])
    if mnemonic == "jev":
        return enc_jev(ops["mask4"], ops["rs"])
    if mnemonic in BR_OPS:
        return enc_br(BR_OPS[mnemonic], ops["pc10"])
    if mnemonic in MISC_OPS:
        return enc_misc(MISC_OPS[mnemonic])
    raise ValueError(f"unknown mnemonic {mnemonic!r}")


def encode_space():
    """Yield every legal 16-bit instruction word exactly once."""
    for op in range(0xC):
        for rd in range(4):
            for rs in range(4):
                if ALU_NAMES[op] in ALU_UNARY and rs:
                    continue  # rs is must-be-zero for unary ops
                yield enc_alu(op, rd, rs)
    for rd in range(4):
        for half in range(2):
            for imm in range(256):
                yield enc_ldi8(rd, half, imm)
    for sub_fn in (enc_pin_out, enc_pin_oe):
        for mask in range(16):
            for val in range(16):
                yield sub_fn(mask, val)
    for fn in (enc_pin_in, enc_lut_read):
        for src in range(16):
            for rd in range(4):
                yield fn(rd, src)
    for rs in range(4):
        yield enc_wait_rs(rs)
    for imm in range(256):
        yield enc_wait_imm(imm)
        yield enc_set_anchor(imm)
        yield enc_bcu_ctrl(imm)
    for mask in range(16):
        for rt in range(4):
            yield enc_sync_event(mask, rt)
    for rd in range(4):
        for sel in range(2):
            yield enc_read_timer(rd, sel)
            yield enc_bcu_crc_rd(rd, sel)
    for r in range(4):
        yield enc_bcu_tx(r)
        yield enc_bcu_rx(r)
        yield enc_bcu_stat(r)
    for sub in range(5):
        for ra in range(4):
            for imm in range(4):
                for rt in range(4):
                    yield enc_mem(sub, ra, imm, rt)
    for r in range(4):
        for addr in range(256):
            yield enc_csr_rd(r, addr)
            yield enc_csr_wr(r, addr)
    for pc in range(1024):
        yield enc_jmp(pc)
        for kind in (BR_OPS["jz"], BR_OPS["jnz"], BR_OPS["call"]):
            yield enc_br(kind, pc)
    for mask in range(16):
        for rs in range(4):
            yield enc_jev(mask, rs)
    for sub in range(3):
        yield enc_misc(sub)


